"""Generate installer/payload.h: the proxy DLL and the SSDF diffs as C arrays.
Usage: embed.py <version> <xinput1_3.dll> <out.h> <diff.ssdf>...
"""
import sys


def array(name, data):
    rows = [', '.join(f'0x{b:02x}' for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f'static const unsigned char {name}[{len(data)}] = {{\n    ' + ',\n    '.join(rows) + '\n};\n'


def main():
    version, dll_path, out_path, diffs = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4:]
    out = ['/* generated by tools/embed.py */', f'#define PAYLOAD_VERSION "{version}"', '#include <stddef.h>']
    out.append(array('payload_dll', open(dll_path, 'rb').read()))
    out.append('static const size_t payload_dll_size = sizeof(payload_dll);')
    for i, path in enumerate(diffs):
        out.append(array(f'payload_diff_{i}', open(path, 'rb').read()))
    out.append('static const struct { const unsigned char *data; size_t size; } payload_diffs[] = {')
    out += [f'    {{ payload_diff_{i}, sizeof(payload_diff_{i}) }},' for i in range(len(diffs))]
    out.append('};')
    out.append('static const size_t payload_diff_count = sizeof(payload_diffs) / sizeof(payload_diffs[0]);')
    open(out_path, 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
